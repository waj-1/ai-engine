"""`requirements.lock` must satisfy every constraint declared in `requirements.txt`.

`requirements.txt` pins 42 packages; a full install resolves ~190. Everything
else floated — including `starlette`, a transitive of `fastapi` pinned nowhere.
On 2026-08-17 a working checkout and a fresh install of the *same*
`requirements.txt` differed in 35 packages (`starlette` 1.3.1 vs 1.6.0,
`anthropic` 0.120.2 vs 0.122.0) and even collected a different number of tests
(5 skipped vs 17). A commit passed locally and failed in CI, and the local run
had been trusted.

`requirements.lock` (generated by `pip-compile`, see `make lock`) is now the
complete resolved set that CI and the prod image install. That only helps while
the two files agree: the moment someone bumps a pin in `requirements.txt` and
forgets to recompile, CI keeps installing the stale lock and the declared
version is a comment. This test moves that divergence to PR time.

It is deliberately offline and dependency-light — no network, no resolver, just
a parse of both files.
"""
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

_ROOT = Path(__file__).resolve().parents[1]
SOURCE = _ROOT / "requirements.txt"
LOCK = _ROOT / "requirements.lock"


def _parse(path: Path) -> dict:
    """Return {canonical_name: Requirement} for every requirement line in *path*.

    pip-compile writes its annotations as `# via ...` continuation lines, and
    both files carry standalone `#` comments, so anything from a `#` onward is
    dropped and blank/indented lines are skipped.
    """
    parsed = {}
    for raw in path.read_text().splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line or line.startswith("-"):
            continue
        req = Requirement(line)
        parsed[canonicalize_name(req.name)] = req
    return parsed


def test_lock_file_exists_and_is_fully_pinned():
    assert LOCK.exists(), (
        f"{LOCK.name} is missing. Generate it with `make lock` — never hand-write it."
    )
    locked = _parse(LOCK)
    floating = sorted(
        name
        for name, req in locked.items()
        if not (len(req.specifier) == 1 and str(req.specifier).startswith("=="))
    )
    assert not floating, (
        "Every line in the lock must be an exact `==` pin — these are not:\n"
        + "\n".join(f"  {n}: {locked[n]}" for n in floating)
        + "\nRegenerate with `make lock`."
    )
    assert len(locked) > len(_parse(SOURCE)), (
        "The lock resolves fewer packages than requirements.txt declares, which "
        "means it is not a full resolution. Regenerate with `make lock`."
    )


def test_every_declared_dependency_is_in_the_lock():
    source, locked = _parse(SOURCE), _parse(LOCK)
    missing = sorted(set(source) - set(locked))
    assert not missing, (
        "requirements.txt declares packages the lock does not contain, so CI and "
        f"the prod image would never install them: {missing}\n"
        "Recompile the lock in the same commit: `make lock`."
    )


def test_locked_versions_satisfy_the_declared_constraints():
    source, locked = _parse(SOURCE), _parse(LOCK)
    conflicts = []
    for name, declared in source.items():
        pinned = locked.get(name)
        if pinned is None:
            continue  # reported by the test above
        version = str(pinned.specifier).lstrip("=")
        # prereleases=True so a pin like `0.60b1` is compared, not silently skipped.
        if not declared.specifier.contains(version, prereleases=True):
            conflicts.append(f"  {name}: requirements.txt wants {declared.specifier}, lock has {version}")
    assert not conflicts, (
        "The lock has drifted from the versions requirements.txt declares:\n"
        + "\n".join(conflicts)
        + "\nThe lock is generated, not edited — fix requirements.txt if the "
        "intent changed, then recompile with `make lock` and commit both files."
    )


def test_declared_extras_survive_into_the_lock():
    """`lmnr[all]` and `uvicorn[standard]` pull materially different trees.

    `--no-strip-extras` keeps them in the lock; if a future recompile drops the
    extras the resolved set silently loses those subtrees.
    """
    source, locked = _parse(SOURCE), _parse(LOCK)
    dropped = sorted(
        name
        for name, declared in source.items()
        if declared.extras and name in locked and not locked[name].extras >= declared.extras
    )
    assert not dropped, (
        "These declare extras in requirements.txt that the lock does not carry: "
        f"{dropped}\nRecompile with `make lock` (which passes --no-strip-extras)."
    )
